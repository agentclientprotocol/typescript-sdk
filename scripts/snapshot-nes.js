#!/usr/bin/env node

import * as fs from "node:fs/promises";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import * as prettier from "prettier";
import ts from "typescript";

// One-time extraction of the NES declarations and their dependency closure.
// This is deliberately separate from generate.js and refuses to overwrite the
// frozen files. Core ACP implementations and schemas must not be copied here.
const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "src/nes/schema");
const release = "schema-v1.25.0";
const revision = "b98857b3f0342915728d7e30d8a7258311054f8f";
const run = promisify(execFile);

function declarations(source) {
  const nodes = new Map();
  for (const node of source.statements) {
    if (ts.isTypeAliasDeclaration(node)) {
      nodes.set(node.name.text, node);
    } else if (ts.isVariableStatement(node)) {
      const [declaration] = node.declarationList.declarations;
      if (ts.isIdentifier(declaration.name)) {
        nodes.set(declaration.name.text, node);
      }
    }
  }
  return nodes;
}

function closure(nodes, roots) {
  const selected = new Set();
  function include(name) {
    if (selected.has(name)) return;
    const node = nodes.get(name);
    if (!node) throw new Error(`Missing NES dependency: ${name}`);
    selected.add(name);
    function visit(child) {
      if (ts.isIdentifier(child) && nodes.has(child.text)) include(child.text);
      ts.forEachChild(child, visit);
    }
    ts.forEachChild(node, visit);
  }
  roots.forEach(include);
  return selected;
}

async function readSource(file) {
  const { stdout } = await run("git", ["show", `${revision}:${file}`], {
    cwd: root,
    maxBuffer: 8 * 1024 * 1024,
  });
  return ts.createSourceFile(file, stdout, ts.ScriptTarget.Latest, true);
}

function extract(nodes, selected) {
  return [...nodes]
    .filter(([name]) => selected.has(name))
    .map(([, node]) => node.getFullText().trim())
    .join("\n\n");
}

const types = declarations(await readSource("src/schema/types.gen.ts"));
const roots = [...types.keys()].filter((name) =>
  /Nes|^Did.*DocumentNotification$|^PositionEncodingKind$/.test(name),
);
if (roots.length !== 52) {
  throw new Error(`Expected the original 52 NES roots, found ${roots.length}`);
}
const selectedTypes = closure(types, roots);
const zodSource = await readSource("src/schema/zod.gen.ts");
const zod = declarations(zodSource);
const selectedZod = closure(
  zod,
  [...selectedTypes].map((name) => `z${name}`),
);
const validators = extract(zod, selectedZod);
const helperImport = zodSource.statements.find(
  (node) =>
    ts.isImportDeclaration(node) &&
    node.moduleSpecifier.text === "../schema-deserialize.js",
);
const helpers = helperImport.importClause.namedBindings.elements
  .map((node) => node.name.text)
  .filter((name) => new RegExp(`\\b${name}\\b`).test(validators));
const banner =
  `// Frozen NES compatibility snapshot from ${release}.\n` +
  "// Not regenerated by npm run generate. See scripts/snapshot-nes.js.\n\n";
const files = new Map([
  ["types.gen.ts", extract(types, selectedTypes)],
  [
    "zod.gen.ts",
    `import { ${helpers.join(", ")} } from "../../schema-deserialize.js";\n` +
      'import * as z from "zod/v4";\n\n' +
      validators,
  ],
]);

await fs.mkdir(output, { recursive: true });
for (const [file, source] of files) {
  const destination = path.join(output, file);
  const options = await prettier.resolveConfig(destination);
  const content = await prettier.format(banner + source, {
    ...options,
    parser: "typescript",
  });
  await fs.writeFile(destination, content, { flag: "wx" });
}
console.log(
  `Snapshotted ${selectedTypes.size} NES types and their validators.`,
);
